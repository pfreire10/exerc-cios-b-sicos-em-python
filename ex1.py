numero1 = input('Digite o primeiro número: ')
numero2 = input('Digite o segundo número: ')

soma = float(numero1) + float(numero2)
diferenca = float(numero1) - float(numero2)
multiplicacao = float(numero1) * float(numero2)
media = (float(numero1) + float(numero2)) / 2

print('A soma dos números é: ', soma)
print('A diferença dos números é: ', diferenca)
print('A multiplicação dos números é: ', multiplicacao)
print('A média dos números é: ', media)